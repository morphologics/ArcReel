def localize_asset_type(value: str, translate: Callable[..., str]) -> str:
    """Replace the internal asset type identifier (e.g. ``"product"``) with the display name in the current language.

    Unregistered type values (not in ``ASSET_SPECS``) pass through unchanged, with no semantic mapping.

    把资产类型内部标识（如 ``"product"``）替换为当前语言显示名。

    未登记的类型值（不在 ``ASSET_SPECS`` 中）原样透传，不做语义映射。
    """
    if value not in ASSET_SPECS:
        return value
    return translate(f"asset_type_{value}")


def normalize_asset_name(name: str) -> str:
    """Normalize an asset name into comparison coordinates (Unicode NFC) -- the point where the coordinate system for
    asset-name equality/membership is defined.

    The same name has two equivalent encodings: NFC (composed form, the main form from web forms and project.json
    registration) and NFD (decomposed form, produced by the macOS file-name system and some input methods). They look
    identical on screen but differ in bytes, so ``==`` and ``in`` judge them unequal; languages heavy in combining
    marks (such as vi among the product's three languages) are especially prone to having both forms. Literal
    comparison must therefore first reduce to the same form, otherwise the user has no way to debug two names that
    look the same.

    Constraint: asset names must be normalized before equality and membership tests. Text names call this function,
    asset table keys call :func:`normalize_asset_bucket`. Normalization happens at read and parse entry points, not
    patched at each comparison point; never compare unnormalized names directly.

    Normalization only converges the encoding form; it doesn't change characters or length semantics, and is the
    identity for pure ASCII names.

    把资产名归一到比对坐标系（Unicode NFC）——资产名判等/判成员的坐标系定义点。

    同一个名字有两种等价编码：NFC（合成形式，网页表单与 project.json 登记侧的主形态）与
    NFD（分解形式，macOS 文件名系统与部分输入法产出）。两者屏幕显示完全相同、字节不同，
    ``==`` 与 ``in`` 判不相等；组合附加符高发的语种（如产品三语中的 vi）尤其容易同时出现
    两种形式。逐字比对因此必须先落到同一形式，否则用户对着两个肉眼一致的名字无从排查。

    约束：资产名判等和成员测试前必须归一化。文本名称调用本函数，资产表 key 调用
    :func:`normalize_asset_bucket`。归一放在读取与解析的入口、不逐个比对点补；不得直接比较
    未归一化的名称。

    归一只做编码形式收敛，不改字、不改长度语义，对纯 ASCII 名是恒等变换。
    """
    return unicodedata.normalize("NFC", name)


def asset_name_comparison_key(name: str) -> str:
    """Project-level asset name equality key: strip surrounding whitespace then converge to Unicode NFC, no case-fold.

    Decides whether two names are the same asset or the same reference; it is also the form of asset names in
    artifact manifest identities and generation bases; changing its return value would change the manifest keys and
    basis digests of all existing artifacts. To decide whether a new name can be registered, use
    :func:`asset_name_namespace_key`.

    项目级资产名判等键：去除两端空白后收敛到 Unicode NFC，不做 case-fold。

    判定两个名字是不是同一个资产、同一处引用，也是产物清单身份与生成依据里资产名的形态；
    改动它的返回值会让存量产物的清单键与依据摘要整体变化。判断新名字能否登记用
    :func:`asset_name_namespace_key`。
    """
    return normalize_asset_name(name.strip())


def asset_name_namespace_key(name: str) -> str:
    """Duplicate key of the project's shared name space: the equality key then case-folded; names differing only in case
    count as duplicates.

    Asset names are used directly as sheet file names (``characters/{name}.png``); the default file systems of macOS
    and Windows are case-insensitive, so ``Alice`` and ``alice`` land on the same file, and the artifact manifest's
    path-uniqueness check also compares by NFC + case-fold. Used only for duplicate checks on add, rename and legacy
    normalization; the asset name itself keeps the case the user wrote.

    项目共享名称空间的判重键：判等键再 case-fold，只差大小写的名字视为重名。

    资产名直接用作资产图文件名（``characters/{name}.png``）；macOS、Windows 默认的文件系统
    不区分大小写，``Alice`` 与 ``alice`` 落到同一个文件，产物清单的路径唯一性校验也按
    NFC + case-fold 比对。只用于新增、改名与旧形态规整的判重；资产名本身保留用户写下的大小写。
    """
    return asset_name_comparison_key(name).casefold()


def build_asset_entry(asset_type: str, description: str, source: Mapping[str, Any] | None = None) -> dict[str, Any]:
    """Build a new entry per ASSET_SPECS: description + empty sheet field + extra fields taken from source or default.

    When source is None only the default values of the extra fields declared in the spec are written (empty string
    for string fields, empty list for list fields); when source is given, it may also override the sheet field.
    Invalid types in source aren't fixed here; the structural validation before writing fails loudly. Types with
    ``supports_derivatives`` enabled always get an empty derivative table.

    按 ASSET_SPECS 构造新条目：description + sheet 字段为空 + extra 字段从 source 取或默认。

    source 为 None 时只写入 spec 中声明的 extra 字段默认值（字符串字段空串、列表字段空列表）；
    source 提供时同时允许覆盖 sheet 字段。source 中的非法类型不在此处修正，由落盘前的结构校验
    fail-loud。开启 ``supports_derivatives`` 的类型一律初始化为空衍生表。
    """
    spec = ASSET_SPECS[asset_type]
    data = source or {}
    entry: dict[str, Any] = {"description": description, spec.sheet_field: data.get(spec.sheet_field, "")}
    for field in spec.extra_string_fields:
        entry[field] = data.get(field, "")
    for field in spec.extra_list_fields:
        value = data.get(field)
        if isinstance(value, list):
            entry[field] = list(value)  # copy, so entry and the caller don't share the same list object / 复制，避免 entry 与调用方共享同一列表对象
        elif value is None:
            entry[field] = []
        else:
            # invalid types pass through; the structural validation before writing fails loudly
            entry[field] = value  # 非法类型透传，由落盘前结构校验 fail-loud
    if spec.supports_derivatives:
        entry[DERIVATIVES_FIELD] = {}
    return entry


def record_asset_aliases(entry: dict[str, Any], aliases: Iterable[str], *, asset_name: str) -> None:
    """Merge names into the asset entry's alias list: de-duplicated by equality key; names equal to the asset name aren't
    recorded, and the asset name itself is removed from the aliases.

    Existing non-string elements are kept as-is, left for the structural validation before writing to report.

    把称呼并入资产条目的别名列表：按判等键去重，与资产名相同的称呼不记，资产名本身移出别名。

    已有的非字符串元素原样保留，交给落盘前的结构校验报出。
    """
    name_key = asset_name_comparison_key(asset_name)
    raw = entry.get(ALIASES_FIELD)
    current = list(raw) if isinstance(raw, list) else []
    kept = [item for item in current if not isinstance(item, str) or asset_name_comparison_key(item) != name_key]
    seen = {asset_name_comparison_key(item) for item in kept if isinstance(item, str)}
    for alias in aliases:
        key = asset_name_comparison_key(alias)
        if not key or key == name_key or key in seen:
            continue
        seen.add(key)
        kept.append(key)
    if kept or ALIASES_FIELD in entry:
        entry[ALIASES_FIELD] = kept


def find_project_asset_name(
    project: object,
    name: str,
    *,
    exclude_asset_type: str | None = None,
    exclude_name: str | None = None,
) -> ProjectAssetNameMatch | None:
    """Find entries among the four ``ASSET_SPECS``-driven project asset types whose name collides with *name* (by
    :func:`asset_name_namespace_key`).

    The hit may be the same-name entry itself or another asset differing only in case; distinguish via
    :meth:`ProjectAssetNameMatch.is_entry`. Entries with an identical equality key take priority over entries
    differing only in case: legacy-registered assets differing only in case can each still be updated in place.
    ``exclude_*`` excludes only one exact on-disk entry, so a rename can ignore itself when checking the target name.
    A malformed bucket is treated as empty; its structural errors are reported separately by DataValidator.

    在 ``ASSET_SPECS`` 驱动的四类项目资产中查找与 *name* 重名的条目（按 :func:`asset_name_namespace_key`）。

    命中的可能是同名条目本身，也可能是只差大小写的另一个资产；用 :meth:`ProjectAssetNameMatch.is_entry`
    区分。判等键相同的条目优先于只差大小写的条目：旧版登记出的只差大小写的资产仍各自可被就地更新。
    ``exclude_*`` 只排除一个确切落盘条目，供 rename 检查目标名时忽略自身。
    畸形 bucket 按空处理，其结构错误由 DataValidator 另行报告。
    """
    if not isinstance(project, dict):
        return None
    target = asset_name_namespace_key(name)
    identity = asset_name_comparison_key(name)
    case_variant: ProjectAssetNameMatch | None = None
    for spec in sorted(ASSET_SPECS.values(), key=lambda item: item.namespace_priority):
        asset_type = spec.asset_type
        bucket = project.get(spec.bucket_key)
        if not isinstance(bucket, dict):
            continue
        for raw_name in bucket:
            if not isinstance(raw_name, str):
                continue
            if asset_type == exclude_asset_type and raw_name == exclude_name:
                continue
            if asset_name_namespace_key(raw_name) != target:
                continue
            match = ProjectAssetNameMatch(asset_type=asset_type, bucket_key=spec.bucket_key, name=raw_name)
            if asset_name_comparison_key(raw_name) == identity:
                return match
            if case_variant is None:
                case_variant = match
    return case_variant


def ensure_project_asset_name_available(
    project: object,
    name: str,
    *,
    requested_asset_type: str | None = None,
    exclude_asset_type: str | None = None,
    exclude_name: str | None = None,
) -> None:
    """Assert that *name* is available in the project's shared name space, otherwise give a structured conflict
    diagnosis.

    断言项目共享名称空间中 *name* 可用，否则给出结构化冲突诊断。"""
    existing = find_project_asset_name(
        project,
        name,
        exclude_asset_type=exclude_asset_type,
        exclude_name=exclude_name,
    )
    if existing is not None:
        raise ProjectAssetNameConflictError(name, existing, requested_asset_type)


def project_asset_name_conflicts(project: object) -> list[tuple[ProjectAssetNameMatch, ProjectAssetNameMatch]]:
    """Return all duplicate pairs in the project's shared name space, in a stable, reproducible order.

    This is the whole-project guard before writing, comparing by the equality key (case-sensitive): legacy versions
    could register assets differing only in case, and such projects already on the current schema aren't migrated;
    comparing by case-fold would reject any write to them. Newly registered names are stopped by case-fold in
    :func:`ensure_project_asset_name_available`.

    返回项目共享名称空间里的所有重名对，顺序稳定可复现。

    这是写盘前的整项目守卫，按判等键（区分大小写）比对：旧版可以登记出只差大小写的资产，已在当前
    schema 的这类项目不做迁移，按 case-fold 比对会让它们的任何写入都被拒。
    新登记的名字由 :func:`ensure_project_asset_name_available` 按 case-fold 拦下。
    """
    if not isinstance(project, dict):
        return []
    first_by_key: dict[str, ProjectAssetNameMatch] = {}
    conflicts: list[tuple[ProjectAssetNameMatch, ProjectAssetNameMatch]] = []
    specs = sorted(ASSET_SPECS.values(), key=lambda spec: spec.namespace_priority)
    for spec in specs:
        bucket = project.get(spec.bucket_key)
        if not isinstance(bucket, dict):
            continue
        for raw_name in bucket:
            if not isinstance(raw_name, str):
                continue
            current = ProjectAssetNameMatch(spec.asset_type, spec.bucket_key, raw_name)
            key = asset_name_comparison_key(raw_name)
            first = first_by_key.setdefault(key, current)
            if first is not current:
                conflicts.append((first, current))
    return conflicts


def ensure_project_asset_namespace(project: object) -> None:
    """Assert that the project's four asset types are globally unique; report the first stable conflict. / 断言项目四类资产全局唯一，报告第一个稳定冲突。"""
    conflicts = project_asset_name_conflicts(project)
    if conflicts:
        first, current = conflicts[0]
        raise ProjectAssetNameConflictError(current.name, first, current.asset_type)


def normalize_asset_bucket(bucket: object) -> dict[str, Any]:
    """Read an asset bucket as a dict whose keys are normalized into comparison coordinates; non-dict malformed values are
    treated as an empty bucket.

    Asset name comparisons are always "name in text x asset table key", and both sides must be in the same
    coordinates to judge correctly. Normalizing once at read covers existing data -- on-disk keys may be in either
    form, and call sites should only care about the comparison result.

    Keys with the same name in different forms merge after normalization (the later-written wins): they refer to the
    same asset name anyway, the asset table shouldn't have two entries, and merging is a repair, not data loss.

    把资产桶读成 key 已归一到比对坐标系的字典；非 dict 的畸形值按空桶处理。

    资产名的比对总是「文本里的名字 × 资产表的 key」，两侧都要在同一坐标系里才判得准。
    读取处归一一次即可覆盖存量数据——落盘的 key 可能是任一形式，而调用点只该关心比对结果。

    同名不同形式的 key 归一后会合并（后写入的胜出）：它们本就指同一个资产名，资产表不应
    同时存在两条，合并即修复而非丢数据。
    """
    if not isinstance(bucket, dict):
        return {}
    return {normalize_asset_name(str(name)): item for name, item in bucket.items()}


def resolve_asset_key(bucket: object, name: str) -> str | None:
    """Resolve the real on-disk key for *name* in the asset bucket by comparison coordinates (NFC); return None if not
    found.

    The write side already stores NFC uniformly (:func:`validate_asset_name`), but keys in existing data may be in
    either encoding form and need no migration: when updating/deleting/checking conflicts by key in place, you can't
    index directly with the normalized name; resolve the real key first, otherwise you'd create a second asset for the
    same visual name or miss a conflict.

    Among existing keys with the same name in several forms, the later-written wins, consistent with the merge
    direction of :func:`normalize_asset_bucket`. A non-dict malformed bucket is treated as empty.

    在资产桶中按比对坐标系（NFC）解析 *name* 对应的真实落盘 key；未命中返回 None。

    写入侧已统一落 NFC（:func:`validate_asset_name`），但存量数据的 key 可能是任一
    编码形式且无需迁移：按 key 就地更新/删除/冲突判定时不能拿归一后的名字直接下标，
    须先解析出真实 key 再操作，否则会对同一个视觉名字新建第二条资产或漏判冲突。

    同名多形式的存量 key 之间后写入的胜出，与 :func:`normalize_asset_bucket` 的合并
    方向一致。非 dict 的畸形桶按空桶处理。
    """
    if not isinstance(bucket, dict):
        return None
    target = normalize_asset_name(name)
    found: str | None = None
    for key in bucket:
        if isinstance(key, str) and normalize_asset_name(key) == target:
            found = key
    return found


def rekey_equivalent_entries[T](bucket: dict[str, T], old_name: str, new_name: str) -> T | None:
    """Rename all keys in the bucket visually equivalent to *old_name* to *new_name*; return the value of that key after
    renaming.

    A rename must absorb the whole cluster of equivalent keys (NFC / NFD coexisting): changing only the one selected by
    :func:`resolve_asset_key` would leave the other equivalent key in the bucket under the old name with stale path
    fields, which a recreated same-name asset might later pick up. The merge direction matches the read side -- the
    later-written value wins, i.e. the one the read side resolves to. When the bucket has no equivalent key, return
    ``None`` and leave the bucket unchanged.

    Rebuild in place rather than pop + assign, keeping the entry's original position in the bucket: the order of
    assets in the JSON is visible to the user.

    把桶中与 *old_name* 视觉等价的全部 key 一并改成 *new_name*，返回改名后该 key 的值。

    改名要收编整簇等价 key（NFC / NFD 并存）：只改 :func:`resolve_asset_key` 选中的那一条，
    另一条等价 key 会顶着旧名带着失效的路径字段留在桶里，之后还可能被重建的同名资产接上。
    合并方向与读侧一致——后写入的值胜出，即读侧解析到的那一条。桶里没有等价 key 时返回
    ``None`` 且不改动桶。

    原地重建而非 pop + 赋值，保留条目在桶中的原位置：JSON 里资产的排列顺序是用户可见的。
    """
    if resolve_asset_key(bucket, old_name) is None:
        return None
    target = normalize_asset_name(old_name)
    rekeyed = {(new_name if normalize_asset_name(key) == target else key): value for key, value in bucket.items()}
    bucket.clear()
    bucket.update(rekeyed)
    return rekeyed[new_name]


def validate_asset_name(name: object) -> str:
    """Validate and normalize (strip + NFC) an asset name; raise ValueError when invalid, return the normalized name when
    valid.

    This is the normalization gate of the registration path: all newly registered/written asset names land in NFC
    coordinates through here (see :func:`normalize_asset_name`), so NFD input no longer gets stored in another
    encoding form, creating visually identical duplicate assets.

    Asset names are used as a single path component throughout: file names (``characters/{name}.png``,
    ``versions/{type}/{name}_v{n}_{ts}.png``) and single-segment path parameters of REST routes. Names containing path
    separators, control characters or ``..`` would produce nested paths and unmatched URLs; Windows also rejects
    ``: * ? " < > |``, trailing dots and reserved device names (CON / COM1 etc., judged by the first dot segment;
    ``CON.backup`` is reserved too). Project directories must be portable across platforms, so these constraints are
    enforced on all platforms and rejected at creation entry points.

    ``]`` is rejected too: references in body text are written ``@[name]``, and parsing ends at the first ``]`` (see
    :func:`lib.script.reference_video.text_parser._iter_mentions`), so a name containing ``]`` would produce a
    reference truncated midway. ``[`` doesn't break anything -- for a name ``[甲``, ``@[[甲]`` still parses back to the
    full ``[甲`` -- so it isn't blocked.

    校验并规范化（strip + NFC）资产名，非法时抛 ValueError，合法时返回规范化后的名字。

    这是登记路径的规范化闸口：所有新登记/新写入的资产名经此落到 NFC 坐标系
    （见 :func:`normalize_asset_name`），NFD 输入不再以另一种编码形式落盘产生
    视觉同名的重复资产。

    资产名全链路被当作单段路径组件使用：文件名（``characters/{name}.png``、
    ``versions/{type}/{name}_v{n}_{ts}.png``）与 REST 路由的单段路径参数。含路径
    分隔符、控制字符或 ``..`` 的名字会产生嵌套路径与无法匹配的 URL；Windows 还会
    拒绝 ``: * ? " < > |``、尾随点与保留设备名（CON / COM1 等，按首个点段判定，
    ``CON.backup`` 同样保留）。项目目录须可跨平台迁移，这些约束在所有平台统一执行，
    并在创建入口拒绝。

    ``]`` 一并拒绝：正文里的引用写作 ``@[名称]``，解析以首个 ``]`` 收尾
    （见 :func:`lib.script.reference_video.text_parser._iter_mentions`），名字含 ``]`` 时写出的
    引用会在中途截断。``[`` 不致坏——名为 ``[甲`` 时 ``@[[甲]`` 仍解析回完整的 ``[甲``——不拦。
    """
    if not isinstance(name, str):
        raise ValueError(f"资产名称必须是字符串，当前为 {type(name).__name__}")
    cleaned = normalize_asset_name(name.strip())
    if not cleaned:
        raise ValueError("资产名称不能为空或仅含空白字符")
    if (
        ".." in cleaned
        or any(c in cleaned for c in ILLEGAL_ASSET_NAME_CHARS)
        or any(ord(c) < 32 or ord(c) == 127 for c in cleaned)
    ):
        raise ValueError(
            f"资产名称 {cleaned!r} 含非法字符：不允许路径分隔符（/ \\）、"
            f'Windows 保留字符（: * ? " < > |）、引用定界符（]）、控制字符或 ..'
        )
    if cleaned.endswith("."):
        raise ValueError(f"资产名称 {cleaned!r} 不能以点结尾（Windows 文件名约束）")
    if cleaned.split(".", 1)[0].upper() in WINDOWS_RESERVED_BASENAMES:
        raise ValueError(f"资产名称 {cleaned!r} 是 Windows 保留设备名（CON/PRN/AUX/NUL/COM1-9/LPT1-9）")
    return cleaned
