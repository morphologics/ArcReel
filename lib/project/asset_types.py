"""Single source of truth for project-level asset type specs (character / scene / prop / product).

``AssetSpec`` describes each asset type's bucket, sheet field, subdirectory, display label, reference fields and
extra fields, shared by ProjectManager's unified asset API, name-space validation and
server/routers/_asset_router_factory. The compatibility constants ASSET_TYPES / BUCKET_KEY / SHEET_KEY are all
derived from ASSET_SPECS.

User-facing display names don't live in the spec: ``localize_asset_type`` uses an injected translate to map the
type identifier to the ``asset_type_*`` key in ``lib/i18n``, so this module has no reverse dependency on i18n.

项目级资产类型规格（character / scene / prop / product）的单一事实源。

``AssetSpec`` 描述每类资产的 bucket、sheet 字段、子目录、显示标签、引用字段与扩展字段，
供 ProjectManager 统一资产 API、名称空间校验和 server/routers/_asset_router_factory 共享。
兼容常量 ASSET_TYPES / BUCKET_KEY / SHEET_KEY 均从 ASSET_SPECS 派生。

面向用户的显示名不落在 spec 里：``localize_asset_type`` 以注入的 translate 把类型标识
映射到 ``lib/i18n`` 的 ``asset_type_*`` key，本模块因而不反向依赖 i18n。
"""

from __future__ import annotations

import unicodedata
from collections.abc import Callable, Iterable, Mapping
from dataclasses import dataclass
from typing import Any


@dataclass(frozen=True)
class AssetSpec:
    """All structural attributes of a single asset type.

    ``extra_string_fields`` is the schema dimension -- the validator uses it to check "these fields, if present, must
    be strings", `_build_asset_entry` uses it to initialize default empty strings, REST PATCH uses it to extend the set
    of updatable fields; ``extra_list_fields`` is the list variant of the schema dimension -- the field, if present,
    must be a "list of strings", `_build_asset_entry` initializes a default empty list, and REST PATCH extends from it
    likewise; ``agent_editable_extra_fields`` is the permission dimension -- the field whitelist of the Agent write
    path (:attr:`agent_writable_fields`) is built from it, **not reusing the schema dimension**. Why the two are
    decoupled: ``reference_image`` / ``reference_images`` are file paths uploaded by the user or generated by the
    system; they are schema-dimension fields but not ``agent_editable_extra_fields`` (the agent shouldn't overwrite
    user-uploaded paths; updates go through a dedicated API, same nature as sheet_field).

    ``original_image_fields`` lists the fields in which this type registers the user's original images (single value
    or list). At execution time reference-to-video expands reference images as "the sheet if there is one, otherwise
    all original images", in field declaration order; types without registered original-image fields (scene / prop)
    produce no reference image candidates when they have no sheet.

    ``in_global_library`` controls whether this type enters the cross-project global asset library (assets table): the
    library's single-image column model only fits "one asset, one image" types, so multi-image list assets (product)
    don't enter for now.

    ``supports_derivatives`` is an optional capability dimension: when enabled, each entry of this type holds a
    derivative table under ``DERIVATIVES_FIELD`` (derivative name -> ``{description, <sheet_field>}``); derivatives
    share the base look's name and identity, are unique only within their owning entry, and are referenced as
    ``本体名/衍生名`` (base/derivative). The mechanism is modeled generically per asset type; currently only character
    enables it (see ``docs/adr/0072``); entries of types without it don't have the field.

    ``label_zh`` serves logger and agent-side strings (both exempt from translation under the i18n rules); user-facing
    asset type display names use the ``asset_type_*`` keys in ``lib/i18n`` and don't reuse this field.

    单一资产类型的所有结构性属性。

    ``extra_string_fields`` 是 schema 维度——validator 据此校验「这些字段若存在须为
    string」、`_build_asset_entry` 据此初始化默认空串、REST PATCH 据此扩展可更新字段集；
    ``extra_list_fields`` 是 schema 维度的列表变体——字段若存在须为「字符串列表」，
    `_build_asset_entry` 初始化默认空列表，REST PATCH 同样据此扩展；
    ``agent_editable_extra_fields`` 是权限维度——Agent 写入路径的字段白名单
    （:attr:`agent_writable_fields`）由它构造，**不复用 schema 维度**。两者解耦的原因：``reference_image`` /
    ``reference_images`` 是用户上传或系统生成的文件路径，是 schema 维度字段但不是
    ``agent_editable_extra_fields``（agent 不该覆写用户上传的路径，更新走专用 API，
    与 sheet_field 同性质）。

    ``original_image_fields`` 列出该类型登记用户原图的字段（单值或列表均可）。参考生视频
    执行期按「有资产图用资产图，否则用全部原图」展开参考图，该顺序即字段声明顺序；未登记
    原图字段的类型（场景 / 道具）没有资产图时就不产生参考图候选。

    ``in_global_library`` 控制该类型是否进入跨项目全局资产库（assets 表）：库的
    单图列模型只兼容「一资产一图」的类型，多图列表型资产（product）暂不进入。

    ``supports_derivatives`` 是可选能力维度：开启后该类型的每个条目在 ``DERIVATIVES_FIELD``
    下持有一张衍生表（衍生名 → ``{description, <sheet_field>}``），衍生共享本体的名字与
    身份，只在所属条目内唯一，引用写作 ``本体名/衍生名``。机制按资产类型通用建模，当前
    只有 character 开启（见 ``docs/adr/0072``）；未开启的类型条目里不出现该字段。

    ``label_zh`` 服务 logger 与 agent 侧字符串（两者按 i18n 规范豁免翻译）；
    面向用户的资产类型显示名走 ``lib/i18n`` 的 ``asset_type_*`` key，不复用此字段。
    """

    asset_type: str
    bucket_key: str
    sheet_field: str
    subdir: str
    label_zh: str
    namespace_priority: int
    reference_list_fields: tuple[str, ...]
    original_image_fields: tuple[str, ...] = ()
    extra_string_fields: tuple[str, ...] = ()
    extra_list_fields: tuple[str, ...] = ()
    agent_editable_extra_fields: tuple[str, ...] = ()
    in_global_library: bool = True
    supports_derivatives: bool = False

    @property
    def agent_writable_fields(self) -> frozenset[str]:
        """Field whitelist of the Agent write paths (`upsert_assets` and the atomic commit of asset extraction).

        `description` is the base common to all types (may be empty, only required when generating a sheet),
        `agent_editable_extra_fields` are each type's string extensions, and types with the derivative capability also
        accept the nested ``DERIVATIVES_FIELD`` (it isn't a string field, so it's not in that tuple). Both Agent entry
        points take the same set; to add a writable field change only this.

        Agent 写入路径（`upsert_assets` 与资产抽取的原子提交）的字段白名单。

        `description` 是所有类型共有的基底（可为空，只在生成资产图时必需），
        `agent_editable_extra_fields` 是各类型的字符串扩展，开启衍生能力的类型另收嵌套的
        ``DERIVATIVES_FIELD``（它不是字符串字段，故不列进那个 tuple）。两条 Agent 入口取同一份，
        新增可写字段只改这里。
        """
        fields = {"description", *self.agent_editable_extra_fields}
        if self.supports_derivatives:
            fields.add(DERIVATIVES_FIELD)
        return frozenset(fields)


