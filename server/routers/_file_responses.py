"""File response shared by public media endpoints: cache header policy + conditional requests (304).

Starlette's ``FileResponse`` sends ETag / Last-Modified and handles Range, but never returns 304 itself; conditional
requests are only evaluated in ``StaticFiles.file_response``. This reuses ``StaticFiles.is_not_modified`` and
``NotModifiedResponse``, and the ETag is also generated by ``FileResponse`` from the same ``stat_result``, so the
revalidation semantics match Starlette's static file serving exactly.

公开媒体端点共用的文件响应：缓存头策略 + 条件请求（304）。

Starlette 的 ``FileResponse`` 会发 ETag / Last-Modified 并处理 Range，但自身从不返回 304；
条件请求只在 ``StaticFiles.file_response`` 里判定。这里复用 ``StaticFiles.is_not_modified``
与 ``NotModifiedResponse``，ETag 也由 ``FileResponse`` 按同一份 ``stat_result`` 生成，
因此与 Starlette 静态文件服务的再验证语义完全一致。
"""

from __future__ import annotations

import mimetypes
import os
from collections.abc import Mapping

from fastapi import Request, Response
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from starlette.staticfiles import NotModifiedResponse

#: URLs with a version key (?v= / ?fp= / versions/ snapshot) never change content; the browser may reuse them forever
#: 带版本键（?v= / ?fp= / versions/ 快照）的 URL 内容不变，浏览器可永久复用
IMMUTABLE_CACHE_CONTROL = "public, max-age=31536000, immutable"
#: URLs without a version key may be overwritten in place: caching is allowed, but must be revalidated before every use
#: (a hit returns 304)
#: 无版本键的 URL 内容可能被原地覆盖：允许缓存，但每次使用前必须再验证（命中返回 304）
REVALIDATE_CACHE_CONTROL = "no-cache"

# Only borrow the decision logic of is_not_modified (If-None-Match first, then If-Modified-Since); no mounting, no
# directory reads; with directory=None construction does not touch the file system
# 只借用 is_not_modified 的判定逻辑（If-None-Match 优先，其次 If-Modified-Since），
# 不挂载、不读目录；directory=None 时构造不触碰文件系统
_CONDITIONAL_CHECKER = StaticFiles(directory=None, check_dir=False)


def guess_media_type(path: str | os.PathLike[str]) -> str:
    """Infer the response media type from the extension, the same way as ``FileResponse``'s default inference.

    The first call in a process loads the system mime table (reads a file), so callers put it in a worker thread.

    按扩展名推断响应的 media type，与 ``FileResponse`` 的默认推断同口径。

    进程内首次调用会加载系统 mime 表（读文件），调用方放进工作线程。
    """
    return mimetypes.guess_type(path)[0] or "application/octet-stream"


def cached_file_response(
    path: str | os.PathLike[str],
    stat_result: os.stat_result,
    request: Request,
    *,
    immutable: bool,
    headers: Mapping[str, str] | None = None,
    media_type: str | None = None,
) -> Response:
    """Build a file response per the cache policy; return 304 when the request's validators match the current file.

    ``stat_result`` and ``media_type`` are obtained by the caller while validating the path (usually in a worker
    thread, the latter with ``guess_media_type``); this function does no I/O. When ``media_type`` is not passed,
    ``FileResponse`` infers it in the current thread.
    Range / If-Range are still handled by ``FileResponse`` itself; an If-None-Match hit returns 304 before Range
    (the evaluation order of RFC 9110 §13.2.2).

    按缓存策略构造文件响应；请求带的校验器与当前文件一致时返回 304。

    ``stat_result`` 与 ``media_type`` 由调用方在校验路径时一并取得（通常在工作线程里，
    后者用 ``guess_media_type``），本函数不做 I/O；不传 ``media_type`` 时由 ``FileResponse``
    在当前线程推断。
    Range / If-Range 仍由 ``FileResponse`` 自身处理；If-None-Match 命中时先于 Range
    返回 304（RFC 9110 §13.2.2 的求值顺序）。
    """
    merged = dict(headers or {})
    merged["Cache-Control"] = IMMUTABLE_CACHE_CONTROL if immutable else REVALIDATE_CACHE_CONTROL
    response = FileResponse(path, headers=merged, media_type=media_type, stat_result=stat_result)
    if request.method in ("GET", "HEAD") and _CONDITIONAL_CHECKER.is_not_modified(response.headers, request.headers):
        return NotModifiedResponse(response.headers)
    return response
