/**
 * Structure needed to refer to entries outside the episode page (backend `with_episode_item_refs`): entry IDs are not shown to creators;
 * the UI composes "Title · 5", using the episode order when the title is empty.
 *
 * 集页面之外指称条目所需的结构（后端 `with_episode_item_refs`）：条目 ID 不给创作者看，
 * 界面拼成「标题 · 5」，标题为空时用播出位置。
 */
export interface EpisodeItemRef {
  episode_title: string;
  episode_position: number;
  /** In-episode ID such as S01 / U02; only used for entries not referred to by position, such as grids. / 集内 ID，如 S01 / U02；只用于宫格这类不按位置指称的条目。 */
  item_id: string;
  /** Current position of the shot or video unit in the episode, starting at 1; null when the entry is no longer in the script. / 分镜或视频单元在本集里的当前位置，从 1 起；条目已不在剧本里时为 null。 */
  item_position: number | null;
  /** The first dozen or so characters of the body; empty string when the entry is no longer in the script. / 正文前十几个字；条目已不在剧本里时为空串。 */
  item_excerpt: string;
  /** Project-relative path of the thumbnail. / 缩略图的项目内相对路径。 */
  item_thumbnail: string | null;
}

export interface EpisodeMeta {
  episode: number;
  title: string;
  script_file: string;
  /** Written by episode_planner at split time: ending hook / suspense */
  hook?: string;
  /** Source range of a split-out episode within the whole source (code point offsets into normalized text); `end` falls in `end_file`, defaulting to `source_file`. / 切出集在整本源文里的原文范围（规范化文本的码位偏移）；`end` 落在 `end_file` 里，缺省同 `source_file`。 */
  source_range?: { source_file?: string; start?: number; end?: number; end_file?: string };
  /**
   * Origin of the episode source: split from the whole source, own source text (uploaded per episode or filled in on the episode page), or no source text.
   * When omitted, inferred from whether source_range is present.
   *
   * 本集原文的来源：切自整本源文、自带原文（逐集上传或在集页填写）、无原文。
   * 缺省按有无 source_range 推断。
   */
  source_origin?: "whole_source" | "own" | "none";
  /** Source file type of an episode with its own source text; only recorded for drama projects. / 自带原文的集的源文件类型，只有剧情演绎项目记录。 */
  source_kind?: "novel" | "screenplay";
  /**
   * Episode planning status. Only stale matters to creators: this episode's source text was replanned or edited,
   * which is a different thing from artifacts going stale (stale of storyboards / videos).
   *
   * 集规划状态。只有 stale 对创作者有意义：这一集的原文已被重新规划或删改，
   * 与产物过期（storyboards / videos 的 stale）是两件事。
   */
  ledger_status?: "planned" | "consumed" | "stale";
  /** Written by episode_planner at split time (drama only) */
  outline?: { story_beats?: string[]; next_episode_teaser?: string };
  /** Instructions of the last prompt authoring, prefilled when opening "Author prompts" / 上一次提示词编写的附加指令，打开「编写提示词」时预填 */
  prompt_authoring_instructions?: string;
  /** Instructions of the last AI script planning, prefilled on regeneration / 上一次 AI 规划脚本的附加指令，重新生成时预填 */
  script_plan_instructions?: string;
  /**
   * Per-episode fields below come from the project summary at read time, on the artifact
   * manifest's terms — the same numbers the studio reads, never persisted to project.json.
   * Optional because the fallback meta some canvases build has no summary behind it.
   *
   * item_count is the episode's content size: number of shots for storyboard mode, number of video units for reference-to-video. / item_count 是该集的内容规模：分镜图生视频是分镜数，参考生视频是视频单元数。
   * The counting basis is decided by the project's generation_mode, the same across all three content modes. / 计数口径由项目的 generation_mode 决定，三种创作类型一致。
   */
  item_count?: number;
  /** Script progress derived from the script_plan and final-script artifact states */
  script_status?: "none" | "segmented" | "generated";
  status?: "draft" | "scripted" | "in_production" | "completed" | "missing";
  duration_seconds?: number;
  storyboards?: ArtifactCount;
  videos?: ArtifactCount;
}

