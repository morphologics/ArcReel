/** Cause of a duration being excluded by coupling constraints; "not in the model's full set" is not in this list, judged by not being in supported_durations. / 时长被联动约束剔除的成因；「型号全集就不含」不在此列，按不在 supported_durations 内判定。 */
export type DurationExclusionReason = "resolution" | "reference";

/**
 * Duration narrowing result and causes under one constraint context, computed and returned by the server from that bucket's video request facts
 * (`lib/generation/video_request_facts.py`); the frontend only looks it up and holds no narrowing rules.
 *
 * 一次约束上下文下的时长收窄结果与成因，由服务端该桶的视频请求事实
 * （`lib/generation/video_request_facts.py`）算好回传；前端只查表，不持有收窄规则。
 */
export interface DurationConstraints {
  /** Effective resolution used for evaluation; null = not narrowed by resolution. / 求值用的生效分辨率；null = 未按分辨率收窄。 */
  resolution: string | null;
  uses_reference_images: boolean;
  /** Narrowing result, ascending. / 收窄结果，升序。 */
  allowed: number[];
  /**
   * Options selectable by the screenplay plan, ascending: usually equal to `allowed`; when duration is fixed by the endpoint, the options borrowed by the plan. Content review uses it
   * to judge out-of-range values, on the same basis as server-side confirmation conversion. Only given by the project endpoint.
   *
   * 剧本规划可选的档位，升序：通常等于 `allowed`；时长由端点固定时是规划借用的档位。内容确认按它
   * 判越档，与服务端确认转换同一口径。只有项目端点给出。
   */
  planning?: number[];
  /** Durations excluded from the full set (keys are seconds as strings) -> cause. / 全集中被剔除的时长（键为秒数字符串）→ 成因。 */
  excluded: Record<string, DurationExclusionReason>;
}

