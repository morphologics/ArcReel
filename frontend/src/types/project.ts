/**
 * Video model capabilities after three-level resolution (project > system settings > system default).
 * Backend: /projects/{name}/video-capabilities in server/routers/projects.py,
 * the project-less variant /providers/video-capabilities in server/routers/providers.py.
 *
 * 三级解析（项目 > 系统设置 > 系统默认）后的视频模型能力。
 * 后端：server/routers/projects.py 的 /projects/{name}/video-capabilities，
 * 无项目变体 server/routers/providers.py 的 /providers/video-capabilities。
 */
export interface VideoCapabilities {
  provider_id: string;
  model: string;
  /** Full set of durations declared by the model, independent of the constraint context; the narrowed result is in duration_constraints. / 型号声明的时长全集，不随约束上下文变化；收窄结果见 duration_constraints。 */
  supported_durations: number[];
  max_duration: number;
  max_reference_images: number;
  /** Effective values (system determination ⊕ user overrides), from the same source as the capabilities the execution layer injects into the backend. / 生效值（系统判定 ⊕ 用户覆盖），与执行层注入 backend 的能力同源。 */
  first_frame: boolean;
  last_frame: boolean;
  source: "registry" | "custom";
  default_duration?: number | null;
  content_mode?: string | null;
  generation_mode?: string | null;
  /** Three-level voice consistency flag (derived from model capability × generation_mode), the server is the sole derivation point. / 声音一致性三级标识（模型能力 × generation_mode 二维派生），服务端唯一派生点。 */
  voice_consistency: VoiceConsistencyTier;
  duration_constraints: DurationConstraints;
  /** The duration dimension is fixed by the endpoint (the ComfyUI workflow sets its own clip length): empty options are not "missing declaration". / 时长这一维由端点固定（ComfyUI workflow 自己定片长）：档位为空集不是「声明缺失」。 */
  duration_endpoint_fixed?: boolean;
  duration_endpoint_fixed_reason?: "endpoint" | null;
}
