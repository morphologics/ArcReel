/**
 * A derivative of a character: another persistent look besides the base look (outfit change, transformation, disguise, etc.). It shares name, voice
 * and identity with the base look, and holds only the change description relative to the base and a sheet, with no original image. The sheet is generated by editing the base look's sheet, or an uploaded finished image can replace it.
 *
 * 角色的一个衍生：本体之外的另一套持续外观（换装、变身、易容等）。与本体共享名字、声音
 * 与身份，只持有相对本体的变化描述与资产图，没有原图。资产图由本体资产图编辑生成，也可以上传成品替换。
 */
export interface CharacterDerivative {
  /** Appearance change relative to the base look, phrased as an image editing instruction. / 相对本体的外观变化，采用图像编辑指令的口吻。 */
  description: string;
  /** Relative path of the derivative sheet; empty when not yet generated. / 衍生资产图相对路径；尚未生成时为空。 */
  character_sheet?: string;
  /** Whether the script writes `@[character/derivative]` or `character/derivative`. Computed on read, not persisted, returned with the entry when reading the project. / 脚本里有没有写 `@[角色/衍生]` 或 `角色/衍生`。读时计算、不落盘，读取项目时随条目返回。 */
  referenced?: boolean;
}

/** Read view of a derivative: registered fields plus "is this image stale relative to the base look's current state". / 衍生的读取视图：登记字段加上「这张图相对本体现状是否已过期」。 */
export interface CharacterDerivativeStatus extends CharacterDerivative {
  /** True when the registered derivative image no longer equals the canonical state; false if never generated. / 已登记的衍生图不再等于规范状态时为真；还没生成过则为假。 */
  stale: boolean;
  /** Artifact manifest status; missing when the registered file is unreadable. / 产物清单状态；登记文件不可读时为 missing。 */
  artifact_status?: "current" | "stale" | "missing" | "blocked";
}

export interface Character {
  description: string;
  character_sheet?: string;
  voice_style?: string;
  reference_image?: string;
  reference_audio?: string;
  /** Set/update time (ISO8601) of the currently effective reference_audio version, stamped mechanically by the backend on write. / reference_audio 当前生效版本的设置/更新时间（ISO8601），由后端在写入时机械戳。 */
  voice_updated_at?: string;
  /**
   * Voice version already acknowledged (ISO8601, the raw voice_updated_at value at dismissal);
   * voice_updated_at later than this counts as a new version.
   */
  /** 已确认到的声音版本（ISO8601，取关闭时的 voice_updated_at 原值）；
   *  voice_updated_at 晚于此值即视为新版本。 */
  voice_notice_dismissed_at?: string;
  /** Derivative table: derivative name -> entry. Derivative names are unique only within this character, written in scripts as `@[character/derivative]`. / 衍生表：衍生名 → 条目。衍生名只在本角色内唯一，脚本中写作 `@[角色/衍生]`。 */
  derivatives?: Record<string, CharacterDerivative>;
  /** Aliases: only for recognizing people during AI planning, not used in references. / 别名：只供 AI 规划时认人参考，不参与引用。 */
  aliases?: string[];
}

