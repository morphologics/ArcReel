import { useTranslation } from "react-i18next";
import { Loader2 } from "lucide-react";
import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogBody,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogTitle,
} from "@/components/ui/alert-dialog";
import type { ScriptOverwrite } from "@/types";
import { itemIdsAsPositionsInText } from "@/utils/episode-display";
import { useProjectsStore } from "@/stores/projects-store";

interface ScriptOverwriteConfirmDialogProps {
  open: boolean;
  overwrite: ScriptOverwrite;
  loading: boolean;
  /** Disables the confirm button in the dialog when preconditions aren't met (e.g. the video model can't be resolved). / 确认前置条件未满足（如视频模型无法解析）时禁用框内确认按钮。 */
  confirmDisabled?: boolean;
  /** Title and confirm button text; defaults to content review's "Overwrite and confirm". / 标题与确认按钮文字；缺省为内容确认的「覆盖并确认」。 */
  title?: string;
  confirmLabel?: string;
  loadingLabel?: string;
  onConfirm: () => void | Promise<void>;
  onCancel: () => void;
}

/**
 * Irreversible confirmation before overwriting an existing final script (content review, ad/short full redo): shows the loss list text generated by the server,
 * only changing entry IDs to their in-episode part; counting follows the same convention as the Agent receipt.
 *
 * 覆盖已有正式脚本前的不可逆确认（内容确认、广告/短片整份重做）：呈现服务端生成的丢失清单文本，
 * 只把条目 ID 改为集内部分，统计口径与 Agent 回执一致。
 */
export function ScriptOverwriteConfirmDialog({
  open,
  overwrite,
  loading,
  confirmDisabled = false,
  title,
  confirmLabel,
  loadingLabel,
  onConfirm,
  onCancel,
}: ScriptOverwriteConfirmDialogProps) {
  const { t } = useTranslation("dashboard");
  const scripts = useProjectsStore((s) => s.currentScripts);

  return (
    <AlertDialog
      open={open}
      onOpenChange={(next) => {
        // Ignore Esc while submitting, so the dialog doesn't disappear while the request is still in flight / 提交中不响应 Esc，避免请求还在途时对话框先消失
        if (!next && !loading) onCancel();
      }}
    >
      <AlertDialogContent size="lg">
        <AlertDialogHeader>
          <AlertDialogTitle>{title ?? t("review_overwrite_title")}</AlertDialogTitle>
        </AlertDialogHeader>
        <AlertDialogBody tabIndex={0} role="region" aria-label={title ?? t("review_overwrite_title")}>
          <AlertDialogDescription>
            <span className="whitespace-pre-line wrap-break-word">{itemIdsAsPositionsInText(overwrite.text, scripts, t)}</span>
          </AlertDialogDescription>
        </AlertDialogBody>
        <AlertDialogFooter>
          <AlertDialogCancel disabled={loading}>{t("common:cancel")}</AlertDialogCancel>
          <AlertDialogAction
            variant="destructive"
            disabled={loading || confirmDisabled}
            onClick={() => void onConfirm()}
          >
            {loading ? <Loader2 aria-hidden data-icon="inline-start" className="animate-spin" /> : null}
            {loading ? (loadingLabel ?? t("review_confirming")) : (confirmLabel ?? t("review_overwrite_confirm"))}
          </AlertDialogAction>
        </AlertDialogFooter>
      </AlertDialogContent>
    </AlertDialog>
  );
}
